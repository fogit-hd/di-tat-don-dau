// Generate deployment-local copies: Render builds frontend/ and backend/ as separate Docker contexts.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..'), check = process.argv.includes('--check')
for (const [source, destinations] of [
  ['shared/experience-contracts.ts', ['backend/src/games/duck-race/experience-contracts.ts', 'frontend/src/games/duck-race/experience-contracts.ts']],
  ['shared/duck-score-motion.ts', ['backend/src/games/duck-race/score-motion.ts', 'frontend/src/games/duck-race/score-motion.ts']],
  ['shared/duck-race.ts', ['backend/src/games/duck-race/contracts.ts', 'frontend/src/games/duck-race/contracts.ts']],
  ['shared/duck-track.ts', ['backend/src/games/duck-race/track.ts', 'frontend/src/games/duck-race/track.ts']],
  ['shared/duck-terrain-shapes.ts', ['backend/src/games/duck-race/terrain-shapes.ts', 'frontend/src/games/duck-race/terrain-shapes.ts']],
  ['shared/duck-motor.ts', ['backend/src/games/duck-race/motor.ts', 'frontend/src/games/duck-race/motor.ts']],
  ['shared/duck-wind.ts', ['backend/src/games/duck-race/wind.ts', 'frontend/src/games/duck-race/wind.ts']],
]) {
  const expected = '// Generated by scripts/sync-duck-contracts.cjs from ' + source + '\n' + fs.readFileSync(path.join(root, source), 'utf8').replace(/\r\n/g, '\n')
  for (const destination of destinations) {
    const file = path.join(root, destination)
    if (check) assert.equal(fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'), expected, destination + ' is stale')
    else fs.writeFileSync(file, expected)
  }
}
console.log(check ? 'Duck Race contracts and road geometry match in both isolated deployments.' : 'Updated Duck Race deployment-local contracts and road geometry.')
